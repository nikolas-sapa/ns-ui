#!/usr/bin/env node

import { spawn } from "node:child_process";
import { parseArgs } from "node:util";
import { readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import { buildIndex } from "../lib/build-index.js";

const REGISTRY_ORIGIN = process.env.NS_UI_REGISTRY || "https://design.helpmarq.com";
const REGISTRY_JSON_URL = `${REGISTRY_ORIGIN}/registry.json`;
const LLMS_TXT_URL = `${REGISTRY_ORIGIN}/llms.txt`;

const PKG_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BUNDLED_INDEX_PATH = join(PKG_ROOT, "data", "registry-index.json");

// Cache lives outside the package (it's per-machine, not per-install) so a
// fresh `npx` re-resolve of the CLI doesn't force a re-fetch every time.
const CACHE_PATH = join(tmpdir(), "ns-ui-cli-cache-v1.json");
const CACHE_TTL_MS = Number(process.env.NS_UI_CACHE_TTL_MS) || 12 * 60 * 60 * 1000; // 12h

// ---------------------------------------------------------------------------
// Colour: TTY + NO_COLOR aware, computed once. Node 22's styleText does not
// reliably auto-detect a non-TTY stream on its own, so gate every call on
// this instead of trusting it to no-op by default.
// ---------------------------------------------------------------------------
const COLOR =
  Boolean(process.stdout.isTTY) &&
  !process.env.NO_COLOR &&
  process.env.TERM !== "dumb";

const CODES = { bold: "1", dim: "2", red: "31", green: "32", yellow: "33", cyan: "36" };
function c(style, text) {
  if (!COLOR) return text;
  return `\x1b[${CODES[style]}m${text}\x1b[0m`;
}

// ---------------------------------------------------------------------------
// Data layer — fully independent of the sibling mcp/ package: no shared
// code, no shared generated file. Three tiers, in order:
//
//   1. On-disk cache (~12h TTL) at CACHE_PATH — avoids a network round trip
//      on every invocation once warm.
//   2. Live fetch of registry.json + llms.txt (the same two public files
//      anyone can already curl from the site) merged by cli/lib/build-index.js
//      — a CLI-owned module, not mcp's. This is what keeps a months-old
//      global install seeing newly-added components.
//   3. The index bundled into this package at publish time
//      (data/registry-index.json, generated by scripts/build-cli-snapshot.mjs
//      from the same two files, read off disk in this repo — see that
//      script) — used only when there's no cache and the network is
//      unreachable, so every command still works fully offline.
//
// `add`'s actual install always hits the network regardless (`shadcn add`
// fetches the component), so tier 3 only affects search/list/info/categories
// staleness, not whether `add` can run.
// ---------------------------------------------------------------------------
let cachedIndex = null;

function readCache() {
  let stat;
  try {
    stat = statSync(CACHE_PATH);
  } catch {
    return null;
  }
  if (Date.now() - stat.mtimeMs > CACHE_TTL_MS) return { stale: true, path: CACHE_PATH };
  try {
    const raw = JSON.parse(readFileSync(CACHE_PATH, "utf8"));
    return { stale: false, registry: raw.registry, llmsText: raw.llmsText };
  } catch {
    return null;
  }
}

function readStaleCache() {
  try {
    const raw = JSON.parse(readFileSync(CACHE_PATH, "utf8"));
    return { registry: raw.registry, llmsText: raw.llmsText };
  } catch {
    return null;
  }
}

function writeCache(registry, llmsText) {
  try {
    mkdirSync(dirname(CACHE_PATH), { recursive: true });
    writeFileSync(CACHE_PATH, JSON.stringify({ registry, llmsText }));
  } catch {
    // Cache is a pure optimization; a write failure (e.g. read-only tmpdir)
    // shouldn't break the command that's otherwise succeeding.
  }
}

async function fetchLive() {
  const [registryRes, llmsRes] = await Promise.all([
    fetch(REGISTRY_JSON_URL),
    fetch(LLMS_TXT_URL),
  ]);
  if (!registryRes.ok) throw new Error(`${REGISTRY_JSON_URL}: ${registryRes.status} ${registryRes.statusText}`);
  if (!llmsRes.ok) throw new Error(`${LLMS_TXT_URL}: ${llmsRes.status} ${llmsRes.statusText}`);
  const [registry, llmsText] = await Promise.all([registryRes.json(), llmsRes.text()]);
  return { registry, llmsText };
}

function loadBundledFallback() {
  const raw = readFileSync(BUNDLED_INDEX_PATH, "utf8");
  return JSON.parse(raw);
}

async function getIndex() {
  if (cachedIndex) return cachedIndex;

  const cached = readCache();
  if (cached && !cached.stale) {
    cachedIndex = buildIndex(cached.registry, cached.llmsText, REGISTRY_ORIGIN);
    return cachedIndex;
  }

  try {
    const { registry, llmsText } = await fetchLive();
    writeCache(registry, llmsText);
    cachedIndex = buildIndex(registry, llmsText, REGISTRY_ORIGIN);
    return cachedIndex;
  } catch (err) {
    const stale = readStaleCache();
    if (stale) {
      console.error(`[ns-ui] couldn't reach ${REGISTRY_ORIGIN} (${err.message}); using cached data.`);
      cachedIndex = buildIndex(stale.registry, stale.llmsText, REGISTRY_ORIGIN);
      return cachedIndex;
    }
    try {
      cachedIndex = loadBundledFallback();
      console.error(
        `[ns-ui] couldn't reach ${REGISTRY_ORIGIN} (${err.message}); using the catalog bundled ` +
          `with this CLI version, which may not include recently added components.`
      );
      return cachedIndex;
    } catch (fallbackErr) {
      console.error(`[ns-ui] couldn't reach ${REGISTRY_ORIGIN} and no offline data is available.`);
      console.error(err.message);
      process.exit(1);
    }
  }
}

