function searchableText(item) {
  return [item.name, item.title, item.description, item.tags.join(" "), item.useWhen]
    .join(" ")
    .toLowerCase();
}

async function cmdSearch(args) {
  let values, positionals;
  try {
    ({ values, positionals } = parseArgs({
      args,
      options: {
        category: { type: "string" },
        collection: { type: "string" },
        limit: { type: "string" },
        help: { type: "boolean", short: "h" },
      },
      strict: true,
      allowPositionals: true,
    }));
  } catch (err) {
    console.error(err.message);
    console.log(COMMAND_HELP.search);
    process.exit(1);
  }

  if (values.help) {
    console.log(COMMAND_HELP.search);
    return;
  }

  const query = positionals.join(" ").trim();
  if (!query) {
    console.error("Usage: npx @nikolas.sapa/ns-ui search <query>");
    process.exit(1);
  }

  const index = await getIndex();
  requireValidCategory(index, values.category);
  requireValidCollection(values.collection);

  const limit = values.limit ? Number(values.limit) : 20;
  if (values.limit && (!Number.isFinite(limit) || limit <= 0)) {
    console.error(`Invalid --limit "${values.limit}". Must be a positive number.`);
    process.exit(1);
  }

  const tokens = query.toLowerCase().split(/\s+/).filter(Boolean);
  const filtered = filterByCategoryAndCollection(index.components, values);
  const matches = filtered.filter((item) => {
    const text = searchableText(item);
    return tokens.every((token) => text.includes(token));
  });

  if (matches.length === 0) {
    console.log(`No components matched "${query}".`);
    return;
  }

  printRows(matches.slice(0, limit));
  const shown = Math.min(limit, matches.length);
  console.log(
    `\n${shown} of ${matches.length} match${matches.length === 1 ? "" : "es"}` +
      (matches.length > shown ? ` (--limit ${limit}, raise it to see more)` : "")
  );
}

