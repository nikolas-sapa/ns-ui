async function cmdInfo(args) {
  let values, positionals;
  try {
    ({ values, positionals } = parseArgs({
      args,
      options: {
        source: { type: "boolean" },
        help: { type: "boolean", short: "h" },
      },
      strict: true,
      allowPositionals: true,
    }));
  } catch (err) {
    console.error(err.message);
    console.log(COMMAND_HELP.info);
    process.exit(1);
  }

  if (values.help) {
    console.log(COMMAND_HELP.info);
    return;
  }

  const name = positionals[0];
  if (!name) {
    console.error("Usage: npx @nikolas.sapa/ns-ui info <name>");
    process.exit(1);
  }

  const index = await getIndex();
  const item = index.components.find((c) => c.name === name);
  if (!item) {
    const suggestions = suggestNames(name, index.components.map((c) => c.name));
    console.error(`Unknown component "${name}".`);
    if (suggestions.length > 0) {
      console.error(`Did you mean: ${suggestions.join(", ")}?`);
    }
    console.error(`Run \`npx @nikolas.sapa/ns-ui search ${name}\` to look it up.`);
    process.exit(1);
  }

  console.log(c("bold", item.title) + c("dim", `  (${item.name})`));
  if (item.kind) console.log(c("dim", item.kind));
  console.log(`\n${item.description}`);
  console.log(`\n${c("bold", "Use when:")} ${item.useWhen}`);
  console.log(`\n${c("bold", "Collection:")} ${item.collection}`);
  console.log(`${c("bold", "Categories:")} ${item.categories.join(", ") || "(none)"}`);
  console.log(`${c("bold", "Tags:")} ${item.tags.join(", ") || "(none)"}`);
  console.log(
    `${c("bold", "Dependencies:")} ${item.dependencies.length ? item.dependencies.join(", ") : "(none)"}`
  );
  console.log(`\n${c("bold", "Props:")}\n${item.props}`);
  console.log(`\n${c("bold", "Install:")} ${item.installCommand}`);

  if (values.source) {
    const url = `${REGISTRY_ORIGIN}/r/${item.name}.json`;
    let res;
    try {
      res = await fetch(url);
    } catch (err) {
      console.error(`\nFailed to fetch source from ${url}`);
      console.error(err.message);
      process.exit(1);
    }
    if (!res.ok) {
      console.error(`\nSource request failed: ${res.status} ${res.statusText}`);
      process.exit(1);
    }
    const json = await res.json();
    const file = json.files?.find((f) => f.path === item.sourcePath) ?? json.files?.[0];
    console.log(`\n${c("bold", `Source (${item.sourcePath}):`)}\n`);
    console.log(file?.content ?? "(no source file returned by the registry)");
  }
}

