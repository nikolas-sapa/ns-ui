async function cmdList(args) {
  let values;
  try {
    ({ values } = parseArgs({
      args,
      options: {
        category: { type: "string" },
        collection: { type: "string" },
        help: { type: "boolean", short: "h" },
      },
      strict: true,
      allowPositionals: false,
    }));
  } catch (err) {
    console.error(err.message);
    console.log(COMMAND_HELP.list);
    process.exit(1);
  }

  if (values.help) {
    console.log(COMMAND_HELP.list);
    return;
  }

  const index = await getIndex();
  requireValidCategory(index, values.category);
  requireValidCollection(values.collection);

  const items = filterByCategoryAndCollection(index.components, values);
  if (items.length === 0) {
    console.log("No components matched those filters.");
    return;
  }

  const categoriesToShow = values.category
    ? index.categories.filter((cat) => cat.id === values.category)
    : index.categories;

  let total = 0;
  for (const cat of categoriesToShow) {
    const inCategory = items.filter((item) => item.categories.includes(cat.id));
    if (inCategory.length === 0) continue;
    console.log(c("bold", `\n${cat.label} (${inCategory.length})`));
    printRows(inCategory);
    total += inCategory.length;
  }

  console.log(`\n${total} component${total === 1 ? "" : "s"} total`);
}

