async function cmdCategories(args) {
  let values;
  try {
    ({ values } = parseArgs({
      args,
      options: { help: { type: "boolean", short: "h" } },
      strict: true,
      allowPositionals: false,
    }));
  } catch (err) {
    console.error(err.message);
    console.log(COMMAND_HELP.categories);
    process.exit(1);
  }

  if (values.help) {
    console.log(COMMAND_HELP.categories);
    return;
  }

  const index = await getIndex();
  const idWidth = Math.max(...index.categories.map((cat) => cat.id.length)) + 2;

  for (const cat of index.categories) {
    const core = index.components.filter(
      (item) => item.categories.includes(cat.id) && item.collection === "core"
    ).length;
    const loud = index.components.filter(
      (item) => item.categories.includes(cat.id) && item.collection === "loud"
    ).length;
    console.log(
      `${c("cyan", cat.id.padEnd(idWidth))}${cat.label.padEnd(20)} ${cat.count} ` +
        c("dim", `(core ${core}, loud ${loud})`)
    );
  }
  console.log(`\n${index.categories.length} categories, ${index.components.length} components total`);
}

