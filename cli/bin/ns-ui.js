// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

async function main() {
  const [command, ...rest] = process.argv.slice(2);

  if (!command || command === "-h" || command === "--help") {
    console.log(HELP);
    return;
  }

  if (command === "-v" || command === "--version") {
    printVersion();
    return;
  }

  switch (command) {
    case "add":
      await cmdAdd(rest);
      return;
    case "list":
      await cmdList(rest);
      return;
    case "search":
      await cmdSearch(rest);
      return;
    case "info":
      await cmdInfo(rest);
      return;
    case "categories":
      await cmdCategories(rest);
      return;
    case "mcp":
      cmdMcp(rest);
      return;
    default:
      console.error(`Unknown command "${command}".\n`);
      console.log(HELP);
      process.exit(1);
  }
}

main();
