async function cmdAdd(args) {
  let values, positionals;
  try {
    ({ values, positionals } = parseArgs({
      args,
      options: {
        "dry-run": { type: "boolean" },
        help: { type: "boolean", short: "h" },
      },
      strict: true,
      allowPositionals: true,
    }));
  } catch (err) {
    console.error(err.message);
    console.log(COMMAND_HELP.add);
    process.exit(1);
  }

  if (values.help) {
    console.log(COMMAND_HELP.add);
    return;
  }

  const names = positionals;
  if (names.length === 0) {
    console.error("Usage: npx @nikolas.sapa/ns-ui add <name> [...names]");
    process.exit(1);
  }

  const index = await getIndex();
  const known = new Set(index.components.map((item) => item.name));
  for (const name of names) {
    if (!known.has(name)) {
      const suggestions = suggestNames(name, [...known]);
      console.error(`Unknown component "${name}".`);
      if (suggestions.length > 0) {
        console.error(`Did you mean: ${suggestions.join(", ")}?`);
      }
      console.error(`Run \`npx @nikolas.sapa/ns-ui search ${name}\` to find the right name.`);
      process.exit(1);
    }
  }

  if (values["dry-run"]) {
    console.log("Dry run — nothing was installed.\n");
    for (const name of names) {
      console.log(`  ${c("cyan", name)}  ${REGISTRY_ORIGIN}/r/${name}.json`);
    }
    return;
  }

  for (const name of names) {
    const url = `${REGISTRY_ORIGIN}/r/${name}.json`;
    console.log(`Installing ${name}...`);
    const code = await runShadcnAdd(url);
    if (code !== 0) {
      process.exit(code);
    }
  }
}

function runShadcnAdd(url) {
  return new Promise((resolve) => {
    const child = spawn("npx", ["shadcn@latest", "add", url], {
      stdio: "inherit",
      shell: process.platform === "win32",
    });
    child.on("error", (err) => {
      console.error(`Failed to run shadcn: ${err.message}`);
      resolve(1);
    });
    child.on("close", (code) => resolve(code ?? 1));
  });
}

