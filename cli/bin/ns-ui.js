function validCategoryIds(index) {
  return index.categories.map((cat) => cat.id);
}

function requireValidCategory(index, id) {
  if (!id) return;
  const ids = validCategoryIds(index);
  if (!ids.includes(id)) {
    console.error(`Unknown category "${id}".`);
    console.error(`Valid categories: ${ids.join(", ")}`);
    process.exit(1);
  }
}

function requireValidCollection(collection) {
  if (!collection) return;
  if (collection !== "core" && collection !== "loud") {
    console.error(`Unknown collection "${collection}". Must be "core" or "loud".`);
    process.exit(1);
  }
}

function filterByCategoryAndCollection(items, { category, collection }) {
  return items.filter((item) => {
    if (category && !item.categories.includes(category)) return false;
    if (collection && item.collection !== collection) return false;
    return true;
  });
}

function printRows(items) {
  const width = Math.max(12, ...items.map((item) => item.name.length)) + 2;
  for (const item of items) {
    const kind = item.kind ? c("dim", ` [${item.kind}]`) : "";
    console.log(`${c("cyan", item.name.padEnd(width))}${item.description || item.title}${kind}`);
  }
}

// Cheap Levenshtein distance for "did you mean" suggestions — no dependency.
function editDistance(a, b) {
  const m = a.length;
  const n = b.length;
  const dp = new Array(n + 1);
  for (let j = 0; j <= n; j++) dp[j] = j;
  for (let i = 1; i <= m; i++) {
    let prev = dp[0];
    dp[0] = i;
    for (let j = 1; j <= n; j++) {
      const tmp = dp[j];
      dp[j] = a[i - 1] === b[j - 1] ? prev : 1 + Math.min(prev, dp[j], dp[j - 1]);
      prev = tmp;
    }
  }
  return dp[n];
}

function suggestNames(unknown, knownNames, max = 3) {
  return knownNames
    .map((name) => ({ name, distance: editDistance(unknown, name) }))
    .filter((entry) => entry.distance <= Math.max(3, Math.ceil(unknown.length / 2)))
    .sort((a, b) => a.distance - b.distance)
    .slice(0, max)
    .map((entry) => entry.name);
}

