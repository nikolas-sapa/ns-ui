import { existsSync, readFileSync } from "node:fs";
import path from "node:path";

/**
 * The component's real source, read off disk at build time (the playground
 * route is statically generated, same as lib/use-when.ts's meta reads).
 *
 * Exists because "npx shadcn add …" is not the only way people want a
 * component: plenty of readers want to see the code, or to paste one file into
 * a project that has no registry wired up at all. The source IS the artifact
 * here — these components install as plain files with no runtime package — so
 * showing it costs nothing and hides nothing.
 */
export function loadSource(name: string): SourceFile | null {
  return read(name, "component.tsx");
}

/**
 * The demo module beside it — the usage example, and the answer to the
 * question `component.tsx` does not answer: what does the call site look
 * like.
 *
 * It is also, specifically, the code for the thing the visitor is looking
 * at. `registry/index.tsx` (generated by scripts/build-index.ts) lazy-imports
 * `./<collection>/<name>/demo` under exactly this key, and that map is what
 * `DemoLazy` renders inside the preview iframe — so the preview and this text
 * cannot drift apart, there is no second copy to maintain.
 *
 * Deliberately not part of the install payload: scripts/build-registry.ts
 * lists only `component.tsx` in each item's `files`, so `npx shadcn add`
 * never writes this file and nothing downstream depends on its contents.
 * That is why it can be read verbatim here rather than rewritten into a
 * cleaned-up snippet — the real bytes are the honest answer, and a derived
 * snippet would be a second artifact to keep in sync with the demo.
 */
export function loadDemoSource(name: string): SourceFile | null {
  return read(name, "demo.tsx");
}

export type SourceFile = { code: string; file: string };

/**
 * Which collection a component lives in is not recorded anywhere this page
 * reads — `registry.json`'s `files[].path` has it, but the lookup there is by
 * name too — so both loaders probe the two directories rather than take a
 * collection argument no caller has.
 */
function read(name: string, basename: string): SourceFile | null {
  for (const collection of ["core", "loud"]) {
    const file = path.join("registry", collection, name, basename);
    const full = path.join(process.cwd(), file);
    if (existsSync(full)) return { code: readFileSync(full, "utf8"), file };
  }
  return null;
}
